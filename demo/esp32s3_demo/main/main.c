/**
 * @brief 应用入口
 */
void app_main(void)
{
    ESP_LOGI(APP_TAG, "esp32s3_demo start");

    if (fct_demo_start() != 0)
    {
        ESP_LOGE(APP_TAG, "fct_demo_start failed");
    }

    if (ble_demo_start() != 0)
    {
        ESP_LOGE(APP_TAG, "ble_demo_start failed");
    }
}

