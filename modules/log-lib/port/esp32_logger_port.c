const logger_driver_t *logger_port_get_driver(void)
{
    static const logger_driver_t driver = {
        .uart_send   = esp32_uart_send,
        .get_time_ms = esp32_get_time_ms,
    };
    return &driver;
}

/****************************************************************************/
/*							Static Functions    						    */
/****************************************************************************/

static uint32_t esp32_get_time_ms(void)
{
    return (uint32_t)(xTaskGetTickCount() * portTICK_PERIOD_MS);
}

static void esp32_uart_send(const char *data, uint32_t length)
{
    if (data && length > 0) {
        ets_printf("%.*s", length, data);
    }
}

