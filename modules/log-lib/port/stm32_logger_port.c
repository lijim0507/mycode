static uint32_t stm32_get_time_ms(void);
static void     stm32_uart_send(const char *data, uint32_t length);

/****************************************************************************/
/*							Global Variables								*/
/****************************************************************************/

/****************************************************************************/
/*							Exported Functions    						    */
/****************************************************************************/

const logger_driver_t *logger_port_get_driver(void)
{
    static const logger_driver_t driver = {
        .uart_send   = stm32_uart_send,
        .get_time_ms = stm32_get_time_ms,
    };
    return &driver;
}

/****************************************************************************/
/*							Static Functions    						    */
/****************************************************************************/

static uint32_t stm32_get_time_ms(void)
{
    return HAL_GetTick();
}

static void stm32_uart_send(const char *data, uint32_t length)
{
    if (data && length > 0) {
        HAL_UART_Transmit(&huart1, (uint8_t *)data, length, HAL_MAX_DELAY);
    }
}

