/**
 * @brief 编码器硬件抽象接口
 */
typedef struct
{
    int     (*init)(void);       /* 初始化硬件，引脚等由 port 文件内部配置 */
    int32_t (*read_count)(void); /* 读取累计计数，允许 32 位回绕 */
    int     (*deinit)(void);     /* 释放硬件 */
} encoder_port_driver_t;

